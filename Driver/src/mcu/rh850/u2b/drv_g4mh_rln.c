/* This function initializes the ASCLIN UART module */
void RH850_G4MH_RLN30_Init(void)
{
    uart_init();
}

/* This function sends and receives the string "Hello World!" */
void RH850_G4MH_RLN30_PutByte(uint8_t c)
{
    while ((RLN30.LST.UINT8 & UART_LST_UTS) != 0U)
    {
    }
    RLN30.LUTDR.UINT16 = c;
    while ((RLN30.LST.UINT8 & UART_LST_UTS) == 0U)
    {
    }
}

uint8_t RH850_G4MH_RLN30_GetByte(void)
{
    while (INTC2.EIC622.BIT.EIRF622 == 0U)
    {
        if ((RLN30.LST.UINT8 & UART_LST_ERR) != 0U)
        {
            /* Has Error */
        }
    }
    if ((RLN30.LST.UINT8 & UART_LST_ERR) != 0U)
    {
        /* Has Error */
    }
    INTC2.EIC622.BIT.EIRF622 = 0U;

    return (uint8_t)RLN30.LURDR.UINT16;
}

int RH850_G4MH_RLN30_GetByte_TimeOut(uint8_t* c, uint32_t timeout)
{
    uint32_t time = 0U;
    while (INTC2.EIC622.BIT.EIRF622 == 0U)
    {
        if ((RLN30.LST.UINT8 & UART_LST_ERR) != 0U)
        {
            /* Has Error */
        }
        else
        {
            time++;
            if(timeout <= time) break;
        }
    }
    if ((RLN30.LST.UINT8 & UART_LST_ERR) != 0U)
    {
        /* Has Error */
    }
    INTC2.EIC622.BIT.EIRF622 = 0U;

    return (uint8_t)RLN30.LURDR.UINT16;
}

void RH850_G4MH_RLN30_DelByte(void)
{
    const unsigned char delChrs[] = { ASCII_CHAR_BS, ASCII_CHAR_DEL, ASCII_CHAR_BS };
    RH850_G4MH_RLN30_PutByte(delChrs[0]);
    RH850_G4MH_RLN30_PutByte(delChrs[1]);
    RH850_G4MH_RLN30_PutByte(delChrs[2]);
}

